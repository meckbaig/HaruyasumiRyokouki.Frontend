/*
  Post-build: emit a localized index.html per locale so link-preview crawlers
  (which do not run JS) get a card in the right language.

  Reads dist/index.html (built by Vite), swaps the block between the
  `<!-- seo:start -->` / `<!-- seo:end -->` markers and the <html lang> for each
  locale, and writes dist/index.<locale>.html. dist/index.html is overwritten
  with the default locale as the no-match fallback. Also writes dist/.htaccess
  with the Apache rules that pick a file by ?lang= / Accept-Language.

  Copy lives in the locale JSON (`app.title`, `app.subtitle`, `seo.description`)
  — the single source of truth shared with the runtime head (src/services/head.js).
*/
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const distIndex = resolve(root, 'dist/index.html')
const distManifest = resolve(root, 'dist/manifest.webmanifest')

const LOCALES = ['ru', 'en', 'ja']
const DEFAULT_LOCALE = 'ru'
const OG_LOCALE = { ru: 'ru_RU', en: 'en_US', ja: 'ja_JP' }

const SEO_MARKERS = /(<!-- seo:start -->)[\s\S]*?(<!-- seo:end -->)/
const HTML_LANG = /<html lang="[^"]*">/
const MANIFEST_HREF = /href="\/manifest\.webmanifest"/

/** Escapes a string for use inside a double-quoted HTML attribute. */
function attr(value) {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function loadMessages(locale) {
  const path = resolve(root, `src/i18n/locales/${locale}.json`)
  return JSON.parse(readFileSync(path, 'utf8'))
}

/** Builds the localized <head> SEO tags for a locale. */
function seoBlock(locale) {
  const m = loadMessages(locale)
  const title = `${m.app.title} — ${m.app.subtitle}`
  const desc = m.seo.description
  const site = m.app.title
  const og = OG_LOCALE[locale]

  return [
    `<title>${attr(title)}</title>`,
    `    <meta name="description" content="${attr(desc)}" />`,
    `    <meta property="og:type" content="website" />`,
    `    <meta property="og:site_name" content="${attr(site)}" />`,
    `    <meta property="og:title" content="${attr(title)}" />`,
    `    <meta property="og:description" content="${attr(desc)}" />`,
    `    <meta property="og:locale" content="${og}" />`,
    `    <meta name="twitter:card" content="summary" />`,
    `    <meta name="twitter:title" content="${attr(title)}" />`,
    `    <meta name="twitter:description" content="${attr(desc)}" />`,
  ].join('\n')
}

/*
  The name an installed app carries comes from the manifest, and the manifest
  format has no way to say a name three times over. So there is one file per
  locale, and each localized index points at its own — which is what puts the
  right name under the icon at the moment the app is installed.

  The runtime swaps this link as well (services/head.js), for a reader who
  changes language and only then installs. Neither can rename an app already on
  a home screen: that name was taken at install time and stays until it is
  installed again.
*/
function renderManifest(base, locale) {
  const m = loadMessages(locale)
  return JSON.stringify(
    {
      ...base,
      lang: locale,
      name: `${m.app.title} — ${m.app.subtitle}`,
      short_name: m.app.title,
      description: m.seo.description,
    },
    null,
    2,
  )
}

function render(template, locale) {
  if (!SEO_MARKERS.test(template)) {
    throw new Error('SEO markers not found in dist/index.html — did the template change?')
  }
  return template
    .replace(SEO_MARKERS, `$1\n    ${seoBlock(locale)}\n    $2`)
    .replace(HTML_LANG, `<html lang="${locale}">`)
    .replace(MANIFEST_HREF, `href="/manifest.${locale}.webmanifest"`)
}

const htaccess = `# Generated by scripts/generate-localized-html.mjs — do not edit by hand.
# Serve a language-specific index so link-preview crawlers and first paint get
# the right locale, then let the SPA take over. Needs mod_rewrite (+ AllowOverride).
RewriteEngine On

# 1) An explicit ?lang= wins — this is what shared links carry.
RewriteCond %{QUERY_STRING} (?:^|&)lang=(ru|en|ja)(?:&|$) [NC]
RewriteRule ^ - [E=PAGELANG:%1]

# 2) Otherwise fall back to the first supported Accept-Language.
RewriteCond %{ENV:PAGELANG} =""
RewriteCond %{HTTP:Accept-Language} \\b(ru|en|ja)\\b [NC]
RewriteRule ^ - [E=PAGELANG:%1]

# 3) Default when nothing matched.
RewriteCond %{ENV:PAGELANG} =""
RewriteRule ^ - [E=PAGELANG:${DEFAULT_LOCALE}]

# Serve real files (assets, the localized html files themselves) untouched. Note:
# no -d test, so the root directory is NOT short-circuited to the default index —
# it must reach the language rule below to honour ?lang on a bare "/".
RewriteCond %{REQUEST_FILENAME} -f
RewriteRule ^ - [L]

# Root and every SPA route -> the chosen localized index. On re-entry that file
# matches the -f rule above and is served, so there is no rewrite loop.
RewriteRule ^ /index.%{ENV:PAGELANG}.html [L]
`

const template = readFileSync(distIndex, 'utf8')
const manifest = JSON.parse(readFileSync(distManifest, 'utf8'))

for (const locale of LOCALES) {
  writeFileSync(resolve(root, `dist/index.${locale}.html`), render(template, locale))
  writeFileSync(
    resolve(root, `dist/manifest.${locale}.webmanifest`),
    renderManifest(manifest, locale),
  )
}
// No-match fallback served for a bare URL without ?lang or Accept-Language.
writeFileSync(distIndex, render(template, DEFAULT_LOCALE))
writeFileSync(resolve(root, 'dist/.htaccess'), htaccess)

console.log(
  `Localized HTML and manifests generated for: ${LOCALES.join(', ')} ` +
    `(default ${DEFAULT_LOCALE}); .htaccess written.`,
)
